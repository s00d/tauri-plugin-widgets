//! Shared harness for the integration tests: a sandboxed MockRuntime app with the plugin,
//! the real ACL, IPC call helpers shaped like the JS API (camelCase JSON) and a channel of
//! the plugin's events.
#![allow(dead_code, unused_imports)]

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::mpsc::{channel, Receiver};
use std::sync::{MutexGuard, OnceLock};
use std::time::Instant;

pub use serde_json::{json, Value};
pub use std::time::Duration;

use tauri::ipc::{CallbackFn, InvokeBody};
use tauri::test::{get_ipc_response, mock_builder, mock_context, noop_assets, MockRuntime};
use tauri::webview::InvokeRequest;
use tauri::{Listener, WebviewWindow};
use tauri_utils::acl::capability::Capability;
use tauri_utils::acl::manifest::{Manifest, PermissionFile};
use tauri_utils::acl::resolved::Resolved;
use tauri_utils::platform::Target;

pub const ROOT: &str = env!("CARGO_MANIFEST_DIR");
/// `tauri.conf` identifier of the test app; the default group is `group.<identifier>`.
pub const IDENTIFIER: &str = "com.example.mockruntime";
pub const DEFAULT_GROUP: &str = "group.com.example.mockruntime";
pub const APPLE: bool = cfg!(any(target_os = "macos", target_os = "ios"));

/// Events the plugin emits to the app (collected by [`App`]).
pub const EVENTS: [&str; 7] = [
    "widget-update",
    "widget-config-push",
    "widget-data-push",
    "widget-state-changed",
    "widget-reload",
    "widget-action",
    "activity-island",
];

/// Every store / data dir the desktop backend can touch, pointed into one temp dir.
/// Set once before the first app is built; the plugin's default group is process-wide too.
pub fn sandbox() -> &'static Path {
    static DIR: OnceLock<tempfile::TempDir> = OnceLock::new();
    DIR.get_or_init(|| {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path();
        let vars = [
            ("HOME", p.to_path_buf()),
            ("XDG_DATA_HOME", p.join("xdg")),
            ("XDG_CACHE_HOME", p.join("xdg-cache")),
            ("APPDATA", p.join("appdata")),
            ("LOCALAPPDATA", p.join("localappdata")),
            ("TAURI_WIDGETS_DATA", p.join("win")),
            ("WIDGET_CONTAINER_ROOT", p.to_path_buf()),
            (
                "WIDGET_APP_GROUP_DATA_FILE",
                p.join("group/widget_data.json"),
            ),
        ];
        for (k, v) in vars {
            // SAFETY: runs once, before any app (and its threads) exists.
            unsafe { std::env::set_var(k, v) };
        }
        dir
    })
    .path()
}

fn permission_files() -> Vec<PermissionFile> {
    let mut paths = vec![Path::new(ROOT).join("permissions/default.toml")];
    paths.extend(
        std::fs::read_dir(Path::new(ROOT).join("permissions/autogenerated/commands"))
            .unwrap()
            .map(|e| e.unwrap().path()),
    );
    paths
        .iter()
        .map(|p| {
            toml::from_str(&std::fs::read_to_string(p).unwrap())
                .unwrap_or_else(|e| panic!("{}: {e}", p.display()))
        })
        .collect()
}

/// Command names the plugin registers, one autogenerated permission file each.
pub fn command_names() -> Vec<String> {
    let dir = Path::new(ROOT).join("permissions/autogenerated/commands");
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .unwrap()
        .map(|e| {
            let p = e.unwrap().path();
            p.file_stem().unwrap().to_string_lossy().into_owned()
        })
        .collect();
    names.sort();
    names
}

/// A plugin event as the app receives it.
#[derive(Debug, Clone)]
pub struct Event {
    pub name: &'static str,
    pub payload: Value,
}

/// The test app: plugin + one `main` window, the IPC entry and the event channel.
///
/// One app at a time per process: every app gets its own store driver, and parallel
/// drivers doing read-modify-write on the one shared store file would lose each other's
/// writes (a real app has a single driver).
pub struct App {
    pub window: WebviewWindow<MockRuntime>,
    pub app: tauri::App<MockRuntime>,
    events: Receiver<Event>,
    _one: MutexGuard<'static, ()>,
}

/// Like the app on exit (`RunEvent::Exit`): queued store writes reach the files before
/// the next app (same sandbox) starts, so a late write never lands in its store.
#[cfg(target_os = "macos")]
impl Drop for App {
    fn drop(&mut self) {
        use tauri::Manager;
        if let Some(w) = self
            .app
            .try_state::<tauri_plugin_widgets::Widget<MockRuntime>>()
        {
            w.inner().flush_store();
        }
    }
}

impl App {
    /// App whose window is granted `widgets:default`.
    pub fn new() -> Self {
        Self::with_permissions(&["widgets:default"])
    }

    pub fn with_permissions(permissions: &[&str]) -> Self {
        Self::build(permissions, false)
    }

    /// App over an empty sandbox: every store, receipt and cache file of earlier apps in
    /// this process is deleted first (a model case starts from nothing).
    pub fn clean() -> Self {
        Self::build(&["widgets:default"], true)
    }

    fn build(permissions: &[&str], wipe: bool) -> Self {
        static ONE_APP: std::sync::Mutex<()> = std::sync::Mutex::new(());
        // A failed test poisons the lock; the next test still runs on its own app.
        let one = ONE_APP.lock().unwrap_or_else(|e| e.into_inner());
        let dir = sandbox();
        if wipe {
            for e in std::fs::read_dir(dir).unwrap().flatten() {
                let p = e.path();
                let _ = if p.is_dir() {
                    std::fs::remove_dir_all(&p)
                } else {
                    std::fs::remove_file(&p)
                };
            }
        }
        let mut ctx = mock_context(noop_assets());
        ctx.config_mut().identifier = IDENTIFIER.into();

        let acl = BTreeMap::from([(
            "widgets".to_string(),
            Manifest::new(permission_files(), None),
        )]);
        let capability: Capability = serde_json::from_value(json!({
            "identifier": "test",
            "windows": ["main"],
            "permissions": permissions,
        }))
        .unwrap();
        let resolved = Resolved::resolve(
            &acl,
            BTreeMap::from([("test".to_string(), capability)]),
            Target::current(),
        )
        .unwrap();
        *ctx.runtime_authority_mut() = tauri::ipc::RuntimeAuthority::new(acl, resolved);

        let app = mock_builder()
            .plugin(tauri_plugin_widgets::init())
            .build(ctx)
            .unwrap();
        let (tx, events) = channel();
        for name in EVENTS {
            let tx = tx.clone();
            app.listen_any(name, move |e| {
                let payload = serde_json::from_str(e.payload()).unwrap_or(Value::Null);
                let _ = tx.send(Event { name, payload });
            });
        }
        let window = tauri::WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .unwrap();
        Self {
            window,
            app,
            events,
            _one: one,
        }
    }

    /// `invoke("plugin:widgets|<cmd>", args)` as the app's JavaScript would.
    pub fn call(&self, cmd: &str, args: Value) -> Result<Value, Value> {
        get_ipc_response(
            &self.window,
            InvokeRequest {
                cmd: format!("plugin:widgets|{cmd}"),
                callback: CallbackFn(0),
                error: CallbackFn(1),
                url: if cfg!(windows) {
                    "http://tauri.localhost"
                } else {
                    "tauri://localhost"
                }
                .parse()
                .unwrap(),
                body: InvokeBody::Json(args),
                headers: Default::default(),
                invoke_key: tauri::test::INVOKE_KEY.to_string(),
            },
        )
        .map(|b| b.deserialize::<Value>().unwrap())
    }

    /// [`Self::call`] that must succeed.
    pub fn ok(&self, cmd: &str, args: Value) -> Value {
        self.call(cmd, args)
            .unwrap_or_else(|e| panic!("{cmd}: {e}"))
    }

    /// Events received so far (non-blocking).
    pub fn drain_events(&self) -> Vec<Event> {
        self.events.try_iter().collect()
    }

    /// Wait (up to `timeout`) for an event `name` whose payload matches `pred`; other
    /// events received meanwhile are dropped.
    pub fn wait_event(
        &self,
        name: &str,
        timeout: Duration,
        pred: impl Fn(&Value) -> bool,
    ) -> Option<Value> {
        let deadline = Instant::now() + timeout;
        loop {
            let left = deadline.checked_duration_since(Instant::now())?;
            match self.events.recv_timeout(left) {
                Ok(e) if e.name == name && pred(&e.payload) => return Some(e.payload),
                Ok(_) => {}
                Err(_) => return None,
            }
        }
    }
}

/// Poll `f` until it returns `Some` or `timeout` passes (no fixed sleeps).
pub fn poll_until<T>(timeout: Duration, mut f: impl FnMut() -> Option<T>) -> Option<T> {
    let deadline = Instant::now() + timeout;
    loop {
        if let Some(v) = f() {
            return Some(v);
        }
        if Instant::now() >= deadline {
            return None;
        }
        std::thread::yield_now();
    }
}

/// An IPC error that is the ACL gate, not the command.
pub fn is_acl_denial(e: &Value) -> bool {
    let s = e.to_string();
    s.contains("not allowed") || s.contains("ACL")
}

/// Every `widget_data.json` under `root` (the store files the host fans out to on macOS).
pub fn store_files(root: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for e in std::fs::read_dir(&dir).into_iter().flatten().flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else if p.file_name().is_some_and(|n| n == "widget_data.json") {
                files.push(p);
            }
        }
    }
    files
}
